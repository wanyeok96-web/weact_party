const modal = { node: null, openId: null };

function openModal(animal) {
  if (modal.openId === animal.id) return;
  modal.openId = animal.id;

  const node = modal.node;
  const { scores, matches } = state.result;
  const rank = matches.findIndex((m) => m.id === animal.id);
  const match = matches[rank];

  const gallery = $('.gallery__track', node);
  gallery.replaceChildren(
    ...animal.photos.map((file, i) =>
      el('img', {
        src: CONFIG.photo(file),
        alt: `${animal.name} 사진 ${i + 1}`,
        width: 800,
        height: 800,
        loading: i ? 'lazy' : 'eager',
        decoding: 'async',
      })
    )
  );
  gallery.scrollLeft = 0;
  updateGalleryCount();

  $('.dog__rank', node).textContent = match
    ? `운명 ${friendNoun(state.answers)} ${rank + 1}위 · 궁합 ${match.percent}%`
    : '';
  $('.dog__species', node).textContent = SPECIES[animal.species].label;
  $('.dog__name', node).textContent = animal.name;
  $('.dog__meta', node).textContent = animalMeta(animal);
  $('.dog__keywords', node).replaceChildren(...animal.keywords.map((k) => el('li', { text: k })));
  $('.dog__intro', node).textContent = animal.intro;

  const facts = [
    ['품종', animal.breed],
    ['중성화', animal.neutered],
    ['예방접종', animal.vaccinated],
  ].filter(([, value]) => value);
  $('.dog__facts', node).replaceChildren(
    ...facts.map(([label, value]) => el('div', {}, [el('dt', { text: label }), el('dd', { text: value })]))
  );

  $('.dog__why ul', node).replaceChildren(
    ...matchReasons(animal, scores, state.answers).map((text) => el('li', { text }))
  );

  $('.radar', node).replaceChildren(radarChart(animal.traits));

  const likes = [
    ['잘해요', animal.good],
    ['좋아해요', animal.likes],
    ['싫어해요', animal.dislikes],
  ].filter(([, value]) => value);
  $('.dog__likes', node).replaceChildren(
    ...likes.flatMap(([label, value]) => [el('dt', { text: label }), el('dd', { text: value })])
  );
  $('.dog__likes', node).closest('.dog__section').hidden = !likes.length;

  $('.dog__details', node).replaceChildren(
    ...DETAIL_SECTIONS.filter((section) => animal.details[section.key]).map((section) =>
      el('div', { class: 'detail' }, [
        el('h5', { text: typeof section.label === 'function' ? section.label(animal) : section.label }),
        el('p', { text: animal.details[section.key] }),
      ])
    )
  );

  const rescue = $('.dog__rescue', node);
  rescue.hidden = !animal.rescue;
  rescue.open = false;
  $('p', rescue).textContent = animal.rescue;

  const profileUrl = withUtm(CONFIG.profileUrl(animal.id));
  node.querySelectorAll('[data-link="apply"], [data-link="profile"]').forEach((link) => {
    link.href = profileUrl;
    link.dataset.animalId = animal.id;
  });

  node.hidden = false;
  document.body.classList.add('is-locked');
  $('.modal__sheet', node).scrollTop = 0;
  $('.modal__close', node).focus({ preventScroll: true });

  track('friend_open', { animalId: animal.id, species: animal.species, rank: rank + 1 });
}

// 5개 성향(1~5점)을 오각형 그래프로 그림
function radarChart(traits) {
  const cx = 180;
  const cy = 136;
  const radius = 84;
  const labelRadius = 106;
  const max = 5;

  const point = (i, r) => {
    const angle = (-90 + (360 / TRAITS.length) * i) * (Math.PI / 180);
    return [cx + r * Math.cos(angle), cy + r * Math.sin(angle)];
  };
  const polygon = (r) => TRAITS.map((_, i) => point(i, typeof r === 'function' ? r(i) : r).join(',')).join(' ');

  const grid = [5, 4, 3, 2, 1].map((level) =>
    svg('polygon', {
      class: level === max ? 'radar__grid radar__grid--outer' : 'radar__grid',
      points: polygon((radius * level) / max),
    })
  );
  const spokes = TRAITS.map((_, i) => {
    const [x, y] = point(i, radius);
    return svg('line', { class: 'radar__spoke', x1: cx, y1: cy, x2: x, y2: y });
  });

  const valueRadius = (i) => (radius * (traits[TRAITS[i].key] || 0)) / max;
  const shape = svg('polygon', { class: 'radar__shape', points: polygon(valueRadius) });
  const dots = TRAITS.map((_, i) => {
    const [x, y] = point(i, valueRadius(i));
    return svg('circle', { class: 'radar__dot', cx: x, cy: y, r: 4 });
  });

  const labels = TRAITS.map((trait, i) => {
    const [x, y] = point(i, labelRadius);
    const dx = x - cx;
    const anchor = Math.abs(dx) < 4 ? 'middle' : dx > 0 ? 'start' : 'end';
    const top = y < cy - radius;
    const bottom = y > cy + radius / 2;
    const labelY = top ? y - 16 : bottom ? y + 4 : y - 6;
    return svg('text', { class: 'radar__label', x, y: labelY, 'text-anchor': anchor }, [
      svg('tspan', { x, text: trait.label }),
      svg('tspan', { class: 'radar__value', x, dy: 19, text: String(traits[trait.key] || '-') }),
    ]);
  });

  const summary = TRAITS.map((trait) => `${trait.label} ${traits[trait.key]}점`).join(', ');
  return svg('svg', { viewBox: '0 0 360 262', role: 'img', 'aria-label': `성향 그래프: ${summary}` }, [
    ...grid,
    ...spokes,
    shape,
    ...dots,
    ...labels,
  ]);
}

function closeModal() {
  if (!modal.node || modal.node.hidden) return;
  modal.node.hidden = true;
  modal.openId = null;
  document.body.classList.remove('is-locked');
}

function requestCloseModal() {
  if (history.state && history.state.inApp) history.back();
  else navigate('result', { replace: true });
}

function updateGalleryCount() {
  const gallery = $('.gallery__track', modal.node);
  const total = gallery.children.length;
  const index = Math.round(gallery.scrollLeft / (gallery.clientWidth || 1)) + 1;
  $('.gallery__count', modal.node).textContent = `${Math.min(index, total)} / ${total}`;
}

