function josa(word, withBatchim, withoutBatchim) {
  const code = word.charCodeAt(word.length - 1) - 0xac00;
  if (code < 0 || code > 11171) return withoutBatchim;
  return code % 28 ? withBatchim : withoutBatchim;
}

function ageLabel(birth) {
  if (!birth) return '';
  const [y, m, d] = birth.split('-').map(Number);
  const now = new Date();
  let months = (now.getFullYear() - y) * 12 + (now.getMonth() + 1 - m);
  if (now.getDate() < d) months -= 1;
  if (months < 12) return `${Math.max(months, 1)}개월`;
  return `${Math.floor(months / 12)}살`;
}

function animalMeta(animal) {
  const body = [animal.size, animal.weight ? `${animal.weight}kg` : ''].filter(Boolean).join(' ');
  return [animal.sex, ageLabel(animal.birth), body].filter(Boolean).join(' · ');
}

