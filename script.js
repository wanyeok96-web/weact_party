function visibleQuestions() {
  return QUESTIONS.filter((q) => !q.when || q.when(state.answers));
}

function computeAxisScores(answers) {
  const scores = {};
  AXIS_ORDER.forEach((axis) => {
    const items = QUESTIONS.filter((q) => q.type === 'likert' && q.axis === axis);
    const sum = items.reduce((acc, q) => acc + likertValue(q, answers[q.id]), 0);
    scores[axis] = ((sum / items.length - 1) / 4) * 100;
  });
  return scores;
}

function likertValue(question, raw) {
  return question.reverse ? 6 - raw : raw;
}

function computeTypeCode(scores, answers) {
  return AXIS_ORDER.map((axis) => {
    let isHigh = scores[axis] > 50;
    if (scores[axis] === 50) {
      const first = QUESTIONS.find((q) => q.axis === axis);
      isHigh = likertValue(first, answers[first.id]) >= 3;
    }
    return isHigh ? AXES[axis].high.letter : AXES[axis].low.letter;
  }).join('');
}

// 사람 점수는 세 문항의 평균이라 양 끝에 잘 닿지 않으므로, 동물 점수도 10~90 범위로 맞춤
function animalAxisScore(animal, axis) {
  return 50 + (animal.scores[axis] - 3) * 20;
}

// 다섯 문항 평균은 가운데로 몰리므로, 양 끝 성향의 아이들도 추천되도록 사람 점수를 바깥쪽으로 넓힘
const USER_STRETCH = 1.3;

function userAxisScore(scores, axis) {
  return Math.min(100, Math.max(0, 50 + (scores[axis] - 50) * USER_STRETCH));
}

function animalLean(animal, axis) {
  if (animal.scores[axis] >= 4) return 1;
  if (animal.scores[axis] <= 2) return -1;
  return 0;
}

function currentPets(answers) {
  return answers.experience === 'current' ? answers.pets || [] : [];
}

function wantedSpecies(answers) {
  const picked = (answers.species || []).filter((sp) => SPECIES[sp]);
  return picked.length ? picked : Object.keys(SPECIES);
}

function rankAnimals(scores, code, answers) {
  const pets = currentPets(answers);
  const species = wantedSpecies(answers);

  const ranked = ANIMALS.filter((animal) => species.includes(animal.species)).map((animal) => {
    let fit = 100;
    AXIS_ORDER.forEach((axis, i) => {
      fit -= WEIGHTS[axis] * Math.abs(userAxisScore(scores, axis) - animalAxisScore(animal, axis));
      const userLean = code[i] === AXES[axis].high.letter ? 1 : -1;
      fit += LEAN_BONUS * userLean * animalLean(animal, axis);
    });

    let excluded = false;
    [['dog', 'dogFriendly'], ['cat', 'catFriendly']].forEach(([pet, key]) => {
      if (!pets.includes(pet)) return;
      if (animal[key] === 'hard') excluded = true;
      else if (animal[key] === 'unknown') fit -= 5;
      else if (animal[key] === 'good') fit += 5;
    });

    if (answers.experience === 'none' && !animal.beginnerOk) fit -= 10;

    fit = Math.max(0, fit);
    // 점수가 3점 이내로 비슷한 아이들끼리는 순서를 섞어 여러 아이가 고르게 소개되도록 함
    return { id: animal.id, fit, excluded, sortKey: fit + Math.random() * 3 };
  });

  const bySortKey = (a, b) => b.sortKey - a.sortKey;
  const pool = ranked.filter((r) => !r.excluded).sort(bySortKey);
  const backup = ranked.filter((r) => r.excluded).sort(bySortKey);

  const top = pool.slice(0, 3);
  while (top.length < 3 && backup.length) top.push({ ...backup.shift(), consult: true });

  return top
    .sort((a, b) => b.fit - a.fit)
    .map((r) => ({ id: r.id, percent: displayPercent(r.fit), consult: Boolean(r.consult) }));
}

// 가산점을 모두 받으면 약 120점까지 올라가므로 0~120점을 60~99%로 환산
function displayPercent(fit) {
  return Math.round(60 + (Math.min(fit, 120) / 120) * 39);
}

function matchReasons(animal, scores, answers) {
  const reasons = AXIS_ORDER
    .map((axis) => ({ axis, diff: Math.abs(userAxisScore(scores, axis) - animalAxisScore(animal, axis)) }))
    .filter((r) => r.diff <= 35)
    .sort((a, b) => a.diff - b.diff)
    .slice(0, 2)
    .map(({ axis }) => {
      const level = animal.scores[axis] >= 4 ? 'high' : animal.scores[axis] <= 2 ? 'low' : 'mid';
      return REASONS[axis][level](animal.name, animal.species);
    });

  if (!reasons.length) {
    reasons.push(`${animal.name}의 이야기를 읽어 보고, 직접 만나 보면 더 잘 알 수 있어요.`);
  }

  const pets = currentPets(answers);
  [['dog', 'dogFriendly'], ['cat', 'catFriendly']].forEach(([pet, key]) => {
    if (!pets.includes(pet)) return;
    const label = SPECIES[pet].label;
    const wa = josa(label, '과', '와');
    if (animal[key] === 'good') reasons.push(`다른 ${label} 친구와도 잘 지내는 아이예요.`);
    else if (animal[key] === 'ok') reasons.push(`함께 사는 ${label}${wa}는 천천히 인사하는 시간이 필요해요.`);
    else if (animal[key] === 'hard') reasons.push(`${label}${wa} 함께 지내기는 어려울 수 있어 꼭 상담이 필요해요.`);
    else reasons.push(`${label}${wa} 지내 본 경험은 아직 확인되지 않았어요. 상담 때 함께 이야기해 보세요.`);
  });

  if (answers.experience === 'none' && !animal.beginnerOk) {
    reasons.push('반려 생활이 처음이라면, 위액트와 충분히 상담한 뒤 만나 보세요.');
  }
  return reasons;
}

