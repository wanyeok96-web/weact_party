function init() {
  document.querySelectorAll('[data-screen]').forEach((node) => {
    screens[node.dataset.screen] = node;
  });
  modal.node = $('#friend-modal');

  document.querySelectorAll('[data-link="more"]').forEach((link) => {
    link.href = withUtm(CONFIG.listUrl);
  });

  document.addEventListener('click', (event) => {
    const action = event.target.closest('[data-action]');
    if (action) {
      const name = action.dataset.action;
      if (name === 'start') {
        state.answers = {};
        state.result = null;
        saveState();
        track('start');
        navigate(`survey/${QUESTIONS[0].id}`);
      } else if (name === 'prev') {
        goPrev();
      } else if (name === 'next') {
        const id = location.hash.split('/')[1];
        if (isAnswered(QUESTIONS.find((q) => q.id === id))) goNext(id);
      } else if (name === 'restart') {
        state.answers = {};
        state.result = null;
        saveState();
        track('restart');
        navigate('start');
      } else if (name === 'share') {
        shareResult();
      } else if (name === 'widen') {
        state.answers.species = Object.keys(SPECIES);
        track('widen');
        finishSurvey();
      } else if (name === 'close-modal') {
        requestCloseModal();
      }
      return;
    }

    const link = event.target.closest('[data-link]');
    if (link) {
      const kind = link.dataset.link;
      if (kind === 'apply' || kind === 'profile') {
        track(`${kind}_click`, { animalId: Number(link.dataset.animalId) });
      } else {
        track('more_click', { from: modal.node.hidden ? 'result' : 'friend' });
      }
    }
  });

  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape' && !modal.node.hidden) requestCloseModal();
  });

  $('.gallery__track', modal.node).addEventListener('scroll', updateGalleryCount, { passive: true });
  window.addEventListener('popstate', render);

  renderSharedBanner();
  if (!location.hash) history.replaceState(null, '', '#start');
  render();
}

document.addEventListener('DOMContentLoaded', init);
